using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using LuminaCleaner.Models;
using Wpf.Ui.Controls;

namespace LuminaCleaner.Modules;

public class TempCleanerModule : CleanerModuleBase
{
    public override string Id => "system_temp";
    public override string Name => "System Temporary Files";
    public override string Description => "Cached temporary files generated by Windows, software installers, and background services.";
    public override string SecurityNotice => "Enterprise Guardrail: Files created or modified within the last 24 hours are strictly preserved to ensure active processes are never disrupted.";
    public override CleanerCategory Category => CleanerCategory.SystemTemp;
    public override SymbolRegular IconSymbol => SymbolRegular.FolderZip24;

    private readonly List<string> _targetDirectories = [];

    public TempCleanerModule()
    {
        string userTemp = Path.GetTempPath();
        if (!string.IsNullOrWhiteSpace(userTemp) && Directory.Exists(userTemp))
        {
            _targetDirectories.Add(userTemp);
        }

        string systemTemp = Environment.ExpandEnvironmentVariables(@"%SystemRoot%\Temp");
        if (Directory.Exists(systemTemp))
        {
            _targetDirectories.Add(systemTemp);
        }
    }

    public override async Task<ModuleScanResult> ScanAsync(
        EngineOptions options,
        IProgress<ScanProgressReport> progress,
        CancellationToken ct)
    {
        var sw = Stopwatch.StartNew();
        IsScanning = true;
        ClearResults();

        var discovered = new List<CleanItemModel>();
        int skippedCount = 0;
        long skippedBytes = 0;
        long totalBytes = 0;

        await Task.Run(() =>
        {
            DateTime now = DateTime.UtcNow;

            foreach (var targetDir in _targetDirectories)
            {
                if (ct.IsCancellationRequested) break;

                foreach (var file in SafeEnumerateFiles(targetDir))
                {
                    if (ct.IsCancellationRequested) break;

                    long length = 0;
                    DateTime lastWriteUtc = DateTime.MinValue;
                    try
                    {
                        length = file.Length;
                        lastWriteUtc = file.LastWriteTimeUtc;
                    }
                    catch
                    {
                        continue;
                    }

                    TimeSpan age = now - lastWriteUtc;
                    if (age < options.AgeSafetyBuffer)
                    {
                        skippedCount++;
                        skippedBytes += length;

                        var skippedItem = new CleanItemModel
                        {
                            FullPath = file.FullName,
                            FileName = file.Name,
                            SizeBytes = length,
                            LastModified = file.LastWriteTime,
                            Category = Category,
                            ModuleName = Name,
                            IsFolder = false,
                            IsSelected = false,
                            Status = CleanItemStatus.SkippedRecent,
                            SkipReason = $"Created/modified within last 24h ({age.TotalHours:N1}h ago) - Active Process Guard"
                        };
                        discovered.Add(skippedItem);
                    }
                    else
                    {
                        var item = new CleanItemModel
                        {
                            FullPath = file.FullName,
                            FileName = file.Name,
                            SizeBytes = length,
                            LastModified = file.LastWriteTime,
                            Category = Category,
                            ModuleName = Name,
                            IsFolder = false,
                            IsSelected = true,
                            Status = CleanItemStatus.Scanned
                        };
                        discovered.Add(item);
                        totalBytes += length;
                    }

                    progress.Report(new ScanProgressReport(
                        file.FullName,
                        discovered.Count,
                        totalBytes,
                        Name,
                        0));
                }
            }
        }, ct);

        foreach (var item in discovered)
        {
            AddDiscoveredItem(item);
        }

        SkippedReasonSummary = skippedCount > 0
            ? $"{skippedCount:N0} files ({CleanItemModel.FormatBytes(skippedBytes)}) protected by 24h safety buffer."
            : "All inspected temporary files are older than 24h.";

        sw.Stop();
        IsScanning = false;
        return new ModuleScanResult(Id, discovered, totalBytes, skippedBytes, skippedCount, sw.Elapsed);
    }

    public override async Task<ModuleCleanResult> CleanAsync(
        EngineOptions options,
        IProgress<CleanProgressReport> progress,
        CancellationToken ct)
    {
        var sw = Stopwatch.StartNew();
        long cleanedBytes = 0;
        int cleanedCount = 0;
        int skippedCount = 0;
        int failedCount = 0;

        var itemsToClean = DiscoveredItems.Where(i => i.IsSelected && i.Status == CleanItemStatus.Scanned).ToList();
        int totalToClean = itemsToClean.Count;

        await Task.Run(() =>
        {
            int index = 0;
            foreach (var item in itemsToClean)
            {
                if (ct.IsCancellationRequested) break;

                index++;
                var (success, skipReason) = SafeDeleteFile(item.FullPath, options.DryRun);

                if (success)
                {
                    item.Status = CleanItemStatus.Cleaned;
                    cleanedBytes += item.SizeBytes;
                    cleanedCount++;
                }
                else
                {
                    item.Status = CleanItemStatus.SkippedLocked;
                    item.SkipReason = skipReason;
                    skippedCount++;
                }

                double pct = totalToClean > 0 ? (double)index / totalToClean * 100.0 : 100.0;
                progress.Report(new CleanProgressReport(
                    item.FullPath,
                    cleanedBytes,
                    item.SizeBytes,
                    index,
                    totalToClean,
                    pct,
                    Name));
            }

            foreach (var dir in _targetDirectories)
            {
                if (ct.IsCancellationRequested) break;
                SafeDeleteEmptyDirectories(dir);
            }
        }, ct);

        UpdateSelectionMetrics();
        sw.Stop();
        return new ModuleCleanResult(Id, cleanedBytes, cleanedCount, skippedCount, failedCount, sw.Elapsed);
    }
}
